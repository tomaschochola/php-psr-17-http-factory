declare(strict_types=1);

namespace TomasChochola\Psr\Http\Factory;

use Override;
use Psr\Container\ContainerInterface;
use Psr\Http\Message\ServerRequestFactoryInterface;
use Psr\Http\Message\StreamFactoryInterface;
use Psr\Http\Message\UriFactoryInterface;
use TomasChochola\Psr\Container\ProviderInterface;

use function assert;

/**
 * @no-named-arguments
 */
readonly class ServerRequestFactoryProvider implements ProviderInterface
{
    #[Override]
    public static function provide(ContainerInterface $container): ServerRequestFactoryInterface
    {
        $streamFactory = $container->get(StreamFactoryInterface::class);
        $uriFactory = $container->get(UriFactoryInterface::class);

        assert($streamFactory instanceof StreamFactoryInterface);
        assert($uriFactory instanceof UriFactoryInterface);

        return new ServerRequestFactory($streamFactory, $uriFactory);
    }
}
